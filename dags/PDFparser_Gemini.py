def _get_report_date_from_pdf(pdf_path):
    """
    Extracts the report date from the first page of the PDF.
    Searches for a specific pattern 'for the date DD.MM.YYYY'.
    Converts the extracted date to 'M/D/YYYY' format.

    Args:
        pdf_path (str): The file path to the PDF document.

    Returns:
        str: The extracted date in 'M/D/YYYY' format, or "Unknown Date" if not found or on error.
    """
    try:
        reader = PdfReader(pdf_path)
        first_page_text = reader.pages[0].extract_text()
        # Search for the date pattern (e.g., "for the date 19.04.2025")
        match = re.search(r"for the date (\d{2}\.\d{2}\.\d{4})", first_page_text)
        if match:
            date_str_ddmmyyyy = match.group(1)
            # Convert DD.MM.YYYY to M/D/YYYY
            day, month, year = date_str_ddmmyyyy.split('.')
            return f"{int(month)}/{int(day)}/{year}"
        print("Warning: Could not find report date in PDF.")
        return "Unknown Date"  # Return a default if date pattern not found
    except Exception as e:
        print(f"Error extracting report date: {e}")
        return "Unknown Date"  # Return a default on any exception

def extract_and_process_tables(pdf_path):
    """
    Extracts all tables from all pages of a specified PDF using tabula-py.
    Also retrieves the report date from the PDF.

    Args:
        pdf_path (str): The file path to the PDF document.

    Returns:
        tuple: A tuple containing:
            - processed_tables (dict): Keys are 'page_X_table_Y', values are raw pandas DataFrames.
            - report_date (str): The extracted report date.
    """
    # pdf_path = "sample input/18.04.25_NLDC_PSP.pdf"  # Hardcoded PDF path
    try:
        reader = PdfReader(pdf_path)
        num_pages = len(reader.pages)
    except Exception as e:
        print(f"Error reading PDF for page count: {e}")
        return {}, "Unknown Date" # Return empty if PDF can't be read

    processed_tables = {}
    print(f"Processing {num_pages} pages...")
    report_date = _get_report_date_from_pdf(pdf_path)

    # Iterate through each page to extract tables
    # tabula pages are 1-indexed
    for page_num in range(1, num_pages + 1):
        try:
            # tabula.read_pdf is the core extraction function.
            # Parameters like guess=True, lattice=True, stream=True are used to maximize table detection.
            tables_on_page = tabula.read_pdf(
                pdf_path,
                pages=page_num,
                multiple_tables=True,
                guess=True,      # Allows tabula to guess table areas, can be less precise but more comprehensive
                lattice=True,    # Assumes clear lines define table cells
                stream=True,     # Useful for tables without clear lines, uses whitespace
                silent=True      # Suppress tabula's command line output for cleaner logs
            )

            # Store each extracted table with a unique key
            for table_idx, table_df in enumerate(tables_on_page):
                if isinstance(table_df, pd.DataFrame): # Ensure tabula returned a DataFrame
                    processed_tables[f"page_{page_num}_table_{table_idx}"] = table_df
            print(f"Processed page {page_num}. Found {len(tables_on_page)} table(s).")

        except Exception as e:
            # Log errors per page, allowing other pages to process
            print(f"Error processing page {page_num}: {str(e)}")

    return processed_tables, report_date

