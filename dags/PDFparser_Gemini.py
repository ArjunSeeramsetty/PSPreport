def identify_and_preprocess_raw_tables(raw_tables_dict):
    """
    Maps raw DataFrames from tabula's output to logical table names.
    Performs generic cleanup (dropping fully empty rows/columns).
    Header processing is deferred to specific transformation functions.

    Args:
        raw_tables_dict (dict): Dictionary of raw DataFrames from extract_and_process_tables.

    Returns:
        dict: Dictionary where keys are logical table names and values are the preprocessed DataFrames.
    """
    identified_tables = {}

    # CRITICAL: This map links tabula's output keys (e.g., 'page_2_table_0')
    # to meaningful logical table names. It MUST be updated based on the
    # actual keys generated by `extract_and_process_tables()` for a given PDF.
    # To get these keys, run: print(raw_tables_dict.keys()) after extraction.
    table_key_to_logical_name_map = {
        'page_2_table_0': 'A. Power Supply Position at All India and Regional level',
        'page_2_table_1': 'B. Frequency Profile (%)',
        'page_2_table_2': 'C. Power Supply Position in States',
        'page_2_table_3': 'D. Transnational Exchanges (MU) - Import(+ve)/Export(-ve)',
        'page_2_table_4': 'E. Import/Export by Regions (in MU) - Import(+ve)/Export(-ve); OD(+)/UD(-)',
        'page_2_table_5': 'F. Generation Outage(MW)',
        'page_2_table_6': 'G. Sourcewise generation (Gross) (MU)',
        'page_2_table_7': 'G. Share of RE and Non-fossil',
        'page_2_table_8': 'H. All India Demand Diversity Factor',
        'page_2_table_9': 'I. All India Peak Demand and shortage at Solar and Non-Solar Hour',
        'page_3_table_0': 'Intra-national Exchange',
        'page_3_table_1': 'International Exchange',
        'page_4_table_0': 'Export From India (in MU)',
        'page_4_table_1': 'Import by India(in MU)',
        'page_4_table_2': 'Net from India(in MU)',
        'page_5_table_0': '15 Min (INSTANTANEOUS) ALL INDIA GRID FREQUENCY, GENERATION & DEMAND MET (SCADA DATA)',
        'page_1_table_0': 'GARBAGE_TO_SKIP' # Example for skipping an irrelevant table
    }

    for tabula_key, df in raw_tables_dict.items():
        logical_name = table_key_to_logical_name_map.get(tabula_key)

        if logical_name and logical_name != 'GARBAGE_TO_SKIP':
            # DataFrames are passed as-is from tabula.
            # Specific header processing will happen in transform_ methods.
            
            # Perform generic cleanup: remove rows/columns that are entirely empty.
            # This is useful as tabula can sometimes create these artifacts.
            if not df.empty:
                df_cleaned = df.dropna(axis=1, how='all').dropna(axis=0, how='all')
                if not df_cleaned.empty: # Ensure DataFrame is not empty after cleanup
                    identified_tables[logical_name] = df_cleaned
                    print(f"Identified table: '{logical_name}' from raw key: {tabula_key}")
                else:
                    print(f"Table from raw key {tabula_key} ('{logical_name}') became empty after cleanup. Skipping.")
            else:
                print(f"Raw table from key {tabula_key} ('{logical_name}') is empty. Skipping.")

        elif logical_name == 'GARBAGE_TO_SKIP':
            print(f"Skipping garbage table: {tabula_key}")
        else:
            # Warn if a table extracted by tabula doesn't have a mapping.
            # This might indicate a new/unexpected table or an incomplete map.
            print(f"No specific mapping found for raw key: {tabula_key}. Contents: \n{df.head(2)}\nSkipping or consider adding to map.")

    print(f"Identified {len(identified_tables)} key tables for transformation.")
    return identified_tables

